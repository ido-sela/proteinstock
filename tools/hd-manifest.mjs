// Lists the 1600px photo copies in img/p/hd (and img/p/hd/g for gallery photos) for the product feed.
// Run after adding copies: node tools/hd-manifest.mjs
import fs from 'node:fs';
const ls = (d, p = '') => (fs.existsSync(d) ? fs.readdirSync(d).filter((f) => f.endsWith('.webp')).map((f) => p + f) : []);
const names = [...ls('img/p/hd'), ...ls('img/p/hd/g', 'g/')].sort();
fs.writeFileSync('api/_lib/hd-images.js', `// Generated by tools/hd-manifest.mjs: photos that have a 1600px copy in img/p/hd.\nexport const HD = new Set(${JSON.stringify(names)});\n`);
console.log(names.length, 'hd photos');
